/* Builds kb.generated.js from the live site's own data (index.html), so the
   terminal can only talk about what the public site already says.
   Run: node build-kb.mjs  (also runs before dev/deploy). */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const html = readFileSync(path.join(here, "../../index.html"), "utf8");
const notes = readFileSync(path.join(here, "kb-notes.md"), "utf8");

const strip = s => String(s || "").replace(/\\'/g, "'").replace(/<\/b>\s*<span>/g, ": ").replace(/<span>/g, " — ").replace(/<\/(div|p)>/g, ". ").replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/\s+/g, " ").replace(/\s*\.(\s*\.)+/g, ".").replace(/\s+([.,])/g, "$1").trim();

function sliceVar(name, endMark) {
  const start = html.indexOf(`var ${name}=`);
  if (start < 0) throw new Error(`index.html: var ${name} not found`);
  const end = html.indexOf(endMark, start);
  return html.slice(start + `var ${name}=`.length, end + endMark.length - 1);
}
function evalData(src) {
  const icons = "var ICO_KNOB='',ICO_CLAUN='',ICO_SKILLS='',ICO_FOOD='',ICO_C2B='',ICO_SWA='',ICO_ANC='',ICO_KP='';";
  return new Function(icons + "return " + src + ";")();
}

const FEATURED = evalData(sliceVar("FEATURED", "\n];"));
const WIP = evalData(sliceVar("WIP", "\n];"));
const WORKROWS = evalData(sliceVar("WORKROWS", "]];")).filter(r => !/⚠/.test(r[1]));

function projectBlock(p, status) {
  const out = [`### ${p.nm}  (key: ${p.k})`, `status: ${status} · badge: ${strip(p.badge)}`,
    `tagline: ${strip(p.tag)}`, `what: ${strip(p.pitch)}`];
  if (p.why) out.push(`why: ${strip(p.why)}`);
  if (p.who) out.push(`for: ${strip(p.who)}`);
  (p.groups || []).forEach(g => out.push(`${strip(g.h)}: ${g.i.map(strip).join("; ")}`));
  if (p.agents) out.push(`agents: ${p.agents.map(a => `${a[0]} (${a[1]})`).join("; ")}`);
  if (p.stack) out.push(strip(p.stack));
  (p.press || []).forEach(x => out.push(`press: "${x.t}" — ${x.pub} (${x.h})`));
  (p.cta || []).filter(c => c.h && c.h !== "#").forEach(c => out.push(`link: ${strip(c.l)} → ${c.h}`));
  return out.join("\n");
}

const aboutStart = html.indexOf("about:{icon");
const aboutEnd = html.indexOf("work:{icon", aboutStart);
const about = strip(html.slice(aboutStart, aboutEnd).replace(/'\+\s*'/g, " ").replace(/<div class="big vbig"><\/div>/, ""))
  .replace(/^about:\{icon:'.*?html:'/, "").replace(/'\},?$/, "");

const kStart = html.indexOf("var KERNEL=");
const kEnd = html.indexOf("var APPS=", kStart);
const kernel = [...html.slice(kStart, kEnd).matchAll(/<span class="ts">\[ ([\d.]+) \]<\/span><span class="tag \w+">(\w+)<\/span><span class="ti">(.*?)<\/span><\/(?:a|div)>/g)]
  .map(m => `- ${m[1]} [${m[2]}] ${strip(m[3]).replace(/ ↗$/, "")}`).join("\n");

const kb = [
  "# captkernel.com — knowledge base (generated from the live site; do not invent beyond it)",
  "## About", about,
  "## Shipped (finished, in the wild)", ...FEATURED.map(p => projectBlock(p, "shipped")),
  "## In progress (building in the open)", ...WIP.map(p => projectBlock(p, "in progress")),
  "## Other systems (short list)", ...WORKROWS.map(r => `- ${r[1]} — ${r[2]} (${r[5]})`),
  "## The Kernel (dispatch log)", kernel,
  notes.trim(),
].join("\n\n");

const keys = [...FEATURED, ...WIP].map(p => p.k);
writeFileSync(path.join(here, "kb.generated.js"),
  "// generated by build-kb.mjs — do not edit\n" +
  `export const KB = ${JSON.stringify(kb)};\n` +
  `export const PROJECT_KEYS = ${JSON.stringify(keys)};\n`);
console.log(`kb.generated.js: ${kb.length} chars, projects: ${keys.join(", ")}`);
